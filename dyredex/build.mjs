// Builds both versions of Dyredex from src/:
//   index.html  the Claude artifact (one file, published as before)
//   web/        the standalone, installable app (PWA); the same folder goes into Capacitor for the App Store
// Run: npm run build
import { build } from "esbuild";
import { readFile, writeFile, mkdir, copyFile, rm } from "node:fs/promises";
import { createHash } from "node:crypto";

const read = f => readFile(new URL(f, import.meta.url), "utf8");
const out = f => new URL(f, import.meta.url);
const pkg = JSON.parse(await read("package.json"));

async function bundle(entry, minify) {
  const r = await build({
    entryPoints: [new URL(entry, import.meta.url).pathname],
    bundle: true, format: "iife", target: ["es2020", "safari15"], platform: "browser",
    minify, write: false, legalComments: "none", charset: "utf8",
    define: { __VERSION__: JSON.stringify(pkg.version) },
  });
  const js = r.outputFiles[0].text;
  if (/<\/script/i.test(js)) throw new Error(`${entry}: bundle contains "</script"`);
  return js;
}

const [head, css, body] = await Promise.all([read("src/head.html"), read("src/app.css"), read("src/body.html")]);
const page = js => `<style>\n${css}</style>\n\n${body}\n<script>\n${js}</script>\n`;

// Claude artifact: the runtime adds the document skeleton.
const claudeJs = await bundle("src/main-claude.js", false);
await writeFile(out("index.html"), `<title>Dyredex</title>\n<meta name="claude:viewport-fit-sides" content="cover">\n${head}${page(claudeJs)}`);

// Standalone web app.
const webJs = await bundle("src/main-web.js", true);
await rm(out("web/"), { recursive: true, force: true });
await mkdir(out("web/icons/"), { recursive: true });
const html = `<!doctype html>
<html lang="da">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1, viewport-fit=cover">
<title>Dyredex</title>
<meta name="description" content="Din egen dyre-dex: tag billeder af dyr, lad AI'en genkende dem og fang dem alle.">
<meta name="theme-color" content="#191b20">
<meta name="apple-mobile-web-app-capable" content="yes">
<meta name="mobile-web-app-capable" content="yes">
<meta name="apple-mobile-web-app-status-bar-style" content="black-translucent">
<meta name="apple-mobile-web-app-title" content="Dyredex">
<link rel="manifest" href="manifest.webmanifest">
<link rel="icon" type="image/png" href="icons/favicon.png">
<link rel="apple-touch-icon" href="icons/apple-touch-icon.png">
${head}</head>
<body>
${page(webJs)}</body>
</html>
`;
await writeFile(out("web/index.html"), html);

const icons = ["icon-192.png", "icon-512.png", "maskable-512.png", "apple-touch-icon.png", "favicon.png"];
for (const f of icons) await copyFile(out(`assets/icons/${f}`), out(`web/icons/${f}`));

await writeFile(out("web/manifest.webmanifest"), JSON.stringify({
  name: "Dyredex", short_name: "Dyredex", lang: "da",
  description: "Tag billeder af dyr, lad AI'en genkende dem og fang dem alle.",
  id: "./", start_url: "./", scope: "./", display: "standalone", orientation: "portrait",
  background_color: "#191b20", theme_color: "#191b20",
  icons: [
    { src: "icons/icon-192.png", sizes: "192x192", type: "image/png" },
    { src: "icons/icon-512.png", sizes: "512x512", type: "image/png" },
    { src: "icons/maskable-512.png", sizes: "512x512", type: "image/png", purpose: "maskable" },
  ],
}, null, 2) + "\n");

// The service worker caches the app shell for offline use. Its cache name changes with the build, so a new
// version replaces the old one on the next visit.
const shell = ["./", "index.html", "manifest.webmanifest", ...icons.map(f => `icons/${f}`)];
const version = createHash("sha256").update(html).digest("hex").slice(0, 12);
await writeFile(out("web/sw.js"), `// Generated by build.mjs. Offline app shell for Dyredex.
const CACHE = "dyredex-${version}";
const SHELL = ${JSON.stringify(shell)};
const FONTS = "dyredex-fonts";
self.addEventListener("install", e => {
  e.waitUntil(caches.open(CACHE).then(c => c.addAll(SHELL)).then(() => self.skipWaiting()));
});
self.addEventListener("activate", e => {
  e.waitUntil(caches.keys().then(keys => Promise.all(keys.filter(k => k !== CACHE && k !== FONTS).map(k => caches.delete(k)))).then(() => self.clients.claim()));
});
self.addEventListener("fetch", e => {
  const req = e.request;
  if (req.method !== "GET") return;
  const url = new URL(req.url);
  // The app itself: network first so updates arrive, cache when offline.
  if (url.origin === location.origin) {
    e.respondWith(fetch(req).then(res => {
      if (res.ok) { const copy = res.clone(); caches.open(CACHE).then(c => c.put(req, copy)); }
      return res;
    }).catch(() => caches.match(req, { ignoreSearch: true }).then(r => r || caches.match("index.html"))));
    return;
  }
  // Fonts: cache after the first load.
  if (url.hostname === "fonts.googleapis.com" || url.hostname === "fonts.gstatic.com") {
    e.respondWith(caches.open(FONTS).then(c => c.match(req).then(hit => hit || fetch(req).then(res => { c.put(req, res.clone()); return res; }))));
  }
  // Everything else (the AI at api.anthropic.com) goes straight to the network.
});
`);

const kb = s => (Buffer.byteLength(s) / 1024).toFixed(0) + " KB";
console.log(`index.html ${kb(await read("index.html"))}, web/index.html ${kb(html)}, sw ${version}`);
